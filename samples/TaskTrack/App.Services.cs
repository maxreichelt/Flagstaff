using CommunityToolkit.Mvvm.Input;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.UI.Dispatching;
using Microsoft.UI.Xaml;
using Microsoft.UI.Xaml.Controls;
using TaskTrack.Services;

namespace TaskTrack;

// Hand-written half of the generated App class (Generated/App.xaml.cs declares the partial hooks).
public partial class App
{
    partial void ConfigureServices(IServiceCollection services)
    {
        services.AddSingleton<InMemoryTaskStore>();
    }

    partial void OnAppLaunched()
    {
        if (Environment.GetEnvironmentVariable("FLAGSTAFF_SMOKE") == "1")
            StartSmokeRun();
    }

    // ── Smoke mode ──────────────────────────────────────────────────────────
    // FLAGSTAFF_SMOKE=1: visit every nav item (plus the task form) 500 ms apart, open each
    // dialog / confirm / toast once, export the task list, expand Settings > Advanced and switch
    // its TabView to "About", dismiss the Projects tip, then exit 0.
    // Any unhandled exception, failed navigation, or faulted LoadCommand exits 1.

    private DispatcherQueueTimer? _smokeTimer;

    private void StartSmokeRun()
    {
        UnhandledException += (_, e) => FailSmoke($"Unhandled exception: {e.Exception}");
        AppDomain.CurrentDomain.UnhandledException += (_, e) => FailSmoke($"Unhandled exception: {e.ExceptionObject}");
        TaskScheduler.UnobservedTaskException += (_, e) => FailSmoke($"Unobserved task exception: {e.Exception}");

        var window = MainWindow ?? throw new InvalidOperationException("MainWindow was not created.");
        var root = window.Content as FrameworkElement;
        var navView = root?.FindName("NavView") as NavigationView;
        var frame = root?.FindName("ContentFrame") as Frame;
        if (navView is null || frame is null)
        {
            FailSmoke("NavView / ContentFrame not found in MainWindow.");
            return;
        }

        frame.NavigationFailed += (_, e) => FailSmoke($"Navigation to {e.SourcePageType} failed: {e.Exception}");

        // One step per tick: each nav item via NavView selection (exercises the generated
        // navigation handler), then the form page that is only reachable from a button, then
        // each overlay once (dialog, confirm, toast) through the same commands the buttons use.
        var steps = new List<Action>();
        foreach (var item in navView.MenuItems.OfType<NavigationViewItem>())
            steps.Add(() => navView.SelectedItem = item);
        steps.Add(() => frame.Navigate(typeof(TaskFormView)));
        steps.Add(() => Execute(frame, "OpenPickerCommand"));            // dialog "Pick assignee"
        steps.Add(() => Execute(frame, "CancelIsPickerOpenCommand"));     // generated by -> cancel
        steps.Add(() => frame.Navigate(typeof(TasksView)));
        steps.Add(() => Execute(frame, "EditCommand", FirstRow(frame)));  // dialog "Edit task"
        steps.Add(() => Execute(frame, "CancelEditCommand"));
        steps.Add(() => Execute(frame, "RequestDeleteCommand", FirstRow(frame))); // confirm "Delete task?"
        steps.Add(() => Execute(frame, "CancelIsDeleteVisibleCommand"));  // generated Cancel
        steps.Add(() => SetFlag(frame, "ShowUpdatedToast"));              // toast ... duration: 3000
        steps.Add(() => Execute(frame, "ExportCommand"));                 // More > Export CSV (+ toast)
        steps.Add(() => frame.Navigate(typeof(SettingsView)));
        steps.Add(() => SetFlag(frame, "ShowAdvanced"));                  // Expander IsExpanded: vm.ShowAdvanced
        steps.Add(() => SetValue(frame, "SelectedTab", 1));               // TabView SelectedIndex: vm.SelectedTab -> "About"
        steps.Add(() => frame.Navigate(typeof(ProjectsView)));
        steps.Add(() => Execute(frame, "DismissHintCommand"));            // card ... load: load(vm.ShowHint) unloads

        var index = 0;
        _smokeTimer = window.DispatcherQueue.CreateTimer();
        _smokeTimer.Interval = TimeSpan.FromMilliseconds(500);
        _smokeTimer.Tick += (_, _) =>
        {
            try
            {
                CheckLoadedPage(frame);
                if (index < steps.Count)
                {
                    steps[index++]();
                    return;
                }

                _smokeTimer.Stop();
                System.Diagnostics.Debug.WriteLine($"[TaskTrack smoke] ran {steps.Count} steps, OK");
                Environment.Exit(0);
            }
            catch (Exception ex)
            {
                FailSmoke(ex.ToString());
            }
        };
        _smokeTimer.Start();
    }

    private static object ViewModelOf(Frame frame) =>
        (frame.Content as Page)?.GetType().GetProperty("ViewModel")?.GetValue(frame.Content)
        ?? throw new InvalidOperationException($"{frame.Content?.GetType().Name ?? "Frame"} has no ViewModel.");

    private static void Execute(Frame frame, string command, object? parameter = null)
    {
        var vm = ViewModelOf(frame);
        if (vm.GetType().GetProperty(command)?.GetValue(vm) is not System.Windows.Input.ICommand cmd)
            throw new InvalidOperationException($"{vm.GetType().Name}.{command} not found.");
        cmd.Execute(parameter);
    }

    private static void SetFlag(Frame frame, string flag) => SetValue(frame, flag, true);

    private static void SetValue(Frame frame, string name, object value)
    {
        var vm = ViewModelOf(frame);
        var property = vm.GetType().GetProperty(name)
            ?? throw new InvalidOperationException($"{vm.GetType().Name}.{name} not found.");
        property.SetValue(vm, value);
    }

    private static object FirstRow(Frame frame)
    {
        var vm = ViewModelOf(frame);
        var rows = vm.GetType().GetProperty("Tasks")?.GetValue(vm) as System.Collections.IList;
        return rows is { Count: > 0 } ? rows[0]! : throw new InvalidOperationException("Tasks is empty.");
    }

    // Release builds of generated pages only log load exceptions (Debug.WriteLine), so inspect the command too.
    private static void CheckLoadedPage(Frame frame)
    {
        if (frame.Content is not Page page)
            return;

        var viewModel = page.GetType().GetProperty("ViewModel")?.GetValue(page);
        var load = viewModel?.GetType().GetProperty("LoadCommand")?.GetValue(viewModel) as IAsyncRelayCommand;
        if (load?.ExecutionTask is { IsFaulted: true } task)
            FailSmoke($"{page.GetType().Name} LoadCommand faulted: {task.Exception}");
    }

    private static void FailSmoke(string message)
    {
        System.Diagnostics.Debug.WriteLine($"[TaskTrack smoke] FAILED: {message}");
        Console.Error.WriteLine($"[TaskTrack smoke] FAILED: {message}");
        Environment.Exit(1);
    }
}
