using System.Text;

namespace Flagstaff.Compiler;

/// <summary>
/// Emits a ViewModel partial class (.g.cs) with [ObservableProperty] fields
/// and [RelayCommand] stubs derived from type inference. Members the hand-written partial already declares
/// (<see cref="ViewContract"/> built with <see cref="UserDeclarations"/>) are skipped.
/// </summary>
public static class ViewModelGenerator
{
    public static string Generate(ViewDecl view, string appNamespace, IEnumerable<string>? extraMembers = null, ViewContract? contract = null)
    {
        var vmType = view.Binding?.ViewModelType;
        if (vmType is null)
            return "";

        var members = TypeInference.InferMembers(view);
        var extras = extraMembers?.ToList() ?? [];
        if (members.Count == 0 && extras.Count == 0)
            return "";
        contract ??= ViewContract.For(view, members, extras);

        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Flagstaff — overwritten on next flagstaff compile.");
        foreach (var line in contract.ViewModelHeader())
            sb.AppendLine(line);
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using CommunityToolkit.Mvvm.ComponentModel;");
        sb.AppendLine("using CommunityToolkit.Mvvm.Input;");
        sb.AppendLine();
        sb.AppendLine($"namespace {appNamespace}.ViewModels;");
        sb.AppendLine();
        sb.AppendLine($"public partial class {vmType} : ObservableObject");
        sb.AppendLine("{");

        var properties = members.Where(m => m.Kind == InferredKind.Property).ToList();
        var propertyLines = 0;
        foreach (var prop in properties)
        {
            var planned = contract.Properties.FirstOrDefault(p => p.Name == prop.Name);
            if (planned?.DeclaredBy is not null)
                continue; // declared in the hand-written partial (FS2016)
            var fieldName = planned?.FieldName ?? ViewContract.FieldNameOf(prop.Name);
            var defaultSuffix = prop.DefaultValue is not null ? $" = {prop.DefaultValue}" : "";
            sb.AppendLine($"    [ObservableProperty] private {prop.CSharpType} {fieldName}{defaultSuffix};");
            propertyLines++;
        }

        // Each [RelayCommand] delegates to an extended partial method the developer implements:
        //   private partial async Task OnSaveAsync() { ... }
        // The onload command is awaited by the Page's Loaded handler; FlowExceptionsToTaskScheduler keeps
        // AsyncRelayCommand from also re-throwing its exception on the UI thread (which would crash the app).
        var loadStem = view.OnLoadTarget is { } onLoad ? TypeInference.OnLoadCommandStem(onLoad) : null;
        var commandLines = new List<string>();
        foreach (var cmd in contract.Commands)
        {
            if (cmd.Delegate is null || cmd.DeclaredBy is not null)
                continue; // dialog cancel commands come with the extras; hand-written commands are skipped (FS2016)
            var attribute = cmd.Stem == loadStem ? "[RelayCommand(FlowExceptionsToTaskScheduler = true)]" : "[RelayCommand]";
            var parameter = cmd.ParameterType is null ? "" : $"{cmd.ParameterType} item";
            // The row goes to the delegate unless the hand-written delegate takes no parameter (ViewContract, FS2016).
            var argument = cmd.ParameterType is null || cmd.CallTarget is null && cmd.DelegateParameterType is null ? "" : "item";
            var target = cmd.CallTarget ?? cmd.Delegate;
            commandLines.Add(cmd.CallReturnsVoid
                ? $"    {attribute} private Task {cmd.Method}({parameter}) {{ {target}({argument}); return Task.CompletedTask; }}"
                : $"    {attribute} private async Task {cmd.Method}({parameter}) {{ await {target}({argument}); }}");
            if (cmd.DelegateMode == DelegateMode.Partial)
                commandLines.Add($"    {cmd.DelegateSignature};");
        }
        // Implemented partial On{X}Async methods no command declares (FS2017): declare them so the build succeeds.
        foreach (var u in contract.UndeclaredPartials)
        {
            var accessibility = u.Accessibility.Length > 0 ? u.Accessibility + " " : "";
            var parameters = string.Join(", ", u.ParameterList.Select(p => $"{p.Type} {p.Name}"));
            commandLines.Add($"    {accessibility}partial {u.Type ?? "Task"} {u.Name}({parameters});");
        }

        if (propertyLines > 0 && commandLines.Count > 0)
            sb.AppendLine();
        foreach (var line in commandLines)
            sb.AppendLine(line);

        foreach (var member in extras)
        {
            if (ViewContract.CancelCommandMethod(member) is { } cancel
                && contract.Commands.Any(c => c.Name == cancel + "Command" && c.DeclaredBy is not null))
                continue;
            sb.AppendLine();
            sb.AppendLine(member.TrimEnd());
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    // Item types (table/list/select ... of T) are collected project-wide by ItemTypeRegistry
    // and emitted once from FlagstaffCompiler.GenerateAppScaffold().
}
