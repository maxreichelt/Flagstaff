namespace Flagstaff.Compiler;

// App shell: MainWindow.xaml, navigation, backdrop.
public sealed partial class XamlGenerator
{
    public string GenerateApp(AppDecl app, string appNamespace)
    {
        _namespace = appNamespace;
        _sb.Clear();
        _indent = 0;

        var nav = app.Members.OfType<NavBlock>().FirstOrDefault();
        var theme = app.Members.OfType<ThemeBlock>().FirstOrDefault();
        var backdrop = GetThemeIdent(theme, "backdrop") ?? "mica";
        var titlebar = GetThemeIdent(theme, "titlebar") ?? "extended";
        var useTitleBar = titlebar == "extended" && theme is not null;

        Line("<!-- Auto-generated by Flagstaff — overwritten on next flagstaff compile. -->");
        Line($"<Window");
        Indent();
        Line($"x:Class=\"{_namespace}.MainWindow\"");
        WriteXamlNamespaces();
        Line($"Title=\"{app.Name}\">");
        Dedent();

        if (theme is not null && backdrop != "none")
            EmitBackdrop(backdrop);

        if (useTitleBar)
        {
            Indent();
            Line("<Grid>");
            Indent();
            Line("<Grid.RowDefinitions>");
            Indent();
            Line("<RowDefinition Height=\"48\" />");
            Line("<RowDefinition Height=\"*\" />");
            Dedent();
            Line("</Grid.RowDefinitions>");
            Line($"<Grid x:Name=\"AppTitleBar\" Grid.Row=\"0\" VerticalAlignment=\"Top\">");
            Indent();
            Line($"<TextBlock Text=\"{Esc(app.Name)}\" VerticalAlignment=\"Center\" Margin=\"16,0\" Style=\"{{StaticResource CaptionTextBlockStyle}}\" />");
            Dedent();
            Line("</Grid>");
        }

        if (nav is not null)
            EmitNav(nav, useTitleBar ? "1" : null);
        else
        {
            if (!useTitleBar)
                Indent();
            Line("<Frame x:Name=\"ContentFrame\" />");
            if (!useTitleBar)
                Dedent();
        }

        if (useTitleBar)
        {
            Dedent();
            Line("</Grid>");
            Dedent();
        }

        Line("</Window>");
        return _sb.ToString();
    }

    private void EmitNav(NavBlock nav, string? gridRow = null)
    {
        if (gridRow is null)
            Indent();
        var paneMode = nav.Mode == NavMode.Top ? "Top" : "Left";
        var rowAttr = gridRow is not null ? $" Grid.Row=\"{gridRow}\"" : "";
        Line($"<NavigationView x:Name=\"NavView\" PaneDisplayMode=\"{paneMode}\" IsBackButtonVisible=\"Collapsed\" IsSettingsVisible=\"False\"{rowAttr}>");
        Indent();

        var brand = nav.Members.OfType<BrandDecl>().FirstOrDefault();
        if (brand is not null)
        {
            Line($"<NavigationView.PaneHeader>");
            Indent();
            Line($"<TextBlock Text=\"{Esc(brand.Text)}\" FontWeight=\"Bold\" Margin=\"12,0\" />");
            Dedent();
            Line("</NavigationView.PaneHeader>");
        }

        Line("<NavigationView.MenuItems>");
        Indent();
        foreach (var link in nav.Members.OfType<NavLinkDecl>())
        {
            var symbol = GetIconSymbol(link.Props);
            var iconAttr = symbol is not null ? $" Icon=\"{symbol}\"" : "";
            Line($"<NavigationViewItem Content=\"{Esc(link.Label)}\" Tag=\"{link.Target}\"{iconAttr} />");
        }
        Dedent();
        Line("</NavigationView.MenuItems>");

        Line("<Frame x:Name=\"ContentFrame\" />");
        Dedent();
        Line("</NavigationView>");
        if (gridRow is null)
            Dedent();
    }

    private void EmitBackdrop(string backdrop)
    {
        Indent();
        Line("<Window.SystemBackdrop>");
        Indent();
        var element = backdrop == "acrylic" ? "DesktopAcrylicBackdrop" : "MicaBackdrop";
        Line($"<{element} />");
        Dedent();
        Line("</Window.SystemBackdrop>");
        Dedent();
    }

    private static string? GetThemeIdent(ThemeBlock? theme, string key)
    {
        if (theme is null) return null;
        var prop = theme.Properties.FirstOrDefault(p => p.Key == key);
        return prop?.Value switch
        {
            IdentValue iv => iv.Name,
            StringValue sv => sv.Value,
            _ => null
        };
    }
}
