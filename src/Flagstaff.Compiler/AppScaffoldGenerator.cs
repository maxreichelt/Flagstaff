using System.Text;

namespace Flagstaff.Compiler;

/// <summary>
/// Generates App.xaml and App.xaml.cs with resource registrations,
/// converter declarations, DI container setup, and ViewModel registrations.
/// </summary>
public static class AppScaffoldGenerator
{
    /// <summary>
    /// Namespaces <c>GlobalUsings.g.cs</c> imports for the whole app, so hand-written partials need no <c>using</c> for
    /// WinUI and CommunityToolkit types (<c>Colors</c>, <c>NavigationEventArgs</c>, <c>PointerPoint</c>, <c>FileSavePicker</c>,
    /// <c>[ObservableProperty]</c>, ...). Chosen so no type name is ambiguous with another entry or with the SDK's implicit
    /// usings (<c>System</c>, <c>System.IO</c>, ...): left out are <c>Windows.UI</c> (its <c>WindowId</c> clashes with
    /// <c>Microsoft.UI.WindowId</c>; only <c>Color</c> is aliased), <c>Windows.System</c> (its <c>DispatcherQueue*</c>
    /// clash with <c>Microsoft.UI.Dispatching</c>), <c>Microsoft.UI.Xaml.Shapes</c> (<c>Path</c> vs <c>System.IO.Path</c>),
    /// <c>Windows.Storage</c> (<c>FileAttributes</c> vs <c>System.IO</c>; <c>StorageProvider</c> and other common names
    /// clash with app types), <c>Windows.Storage.Streams</c> (<c>Buffer</c> vs <c>System.Buffer</c>) and
    /// <c>System.ComponentModel</c> (<c>BindableAttribute</c> vs <c>Microsoft.UI.Xaml.Data</c>). <c>Windows.Graphics.Imaging</c>
    /// (<c>BitmapEncoder</c>, <c>SoftwareBitmap</c>) shares no type name with any of them (checked against the Windows SDK
    /// 22621 projection, Windows App SDK 1.7, CommunityToolkit.Mvvm and the .NET 10 reference assemblies; see the README).
    /// </summary>
    public static readonly IReadOnlyList<string> GlobalUsingNamespaces =
    [
        "System.Collections.ObjectModel",
        "CommunityToolkit.Mvvm.ComponentModel",
        "CommunityToolkit.Mvvm.Input",
        "Microsoft.Extensions.DependencyInjection",
        "Microsoft.UI",
        "Microsoft.UI.Dispatching",
        "Microsoft.UI.Input",
        "Microsoft.UI.Xaml",
        "Microsoft.UI.Xaml.Controls",
        "Microsoft.UI.Xaml.Controls.Primitives",
        "Microsoft.UI.Xaml.Data",
        "Microsoft.UI.Xaml.Input",
        "Microsoft.UI.Xaml.Media",
        "Microsoft.UI.Xaml.Media.Imaging",
        "Microsoft.UI.Xaml.Navigation",
        "Windows.Foundation",
        "Windows.Graphics.Imaging",
        "Windows.Storage.Pickers",
    ];

    /// <summary>
    /// <c>GlobalUsings.g.cs</c>: <see cref="GlobalUsingNamespaces"/>, <c>Color</c> = <c>Windows.UI.Color</c>, and the app's
    /// <c>ViewModels</c> namespace (item types, ViewModels) when the generated code declares anything there.
    /// </summary>
    public static OutputFile GenerateGlobalUsings(string appNamespace, bool hasViewModelsNamespace)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Flagstaff — overwritten on next flagstaff compile.");
        sb.AppendLine("// Namespaces every C# file of the app can use without a 'using' directive.");
        foreach (var ns in GlobalUsingNamespaces)
            sb.AppendLine($"global using {ns};");
        sb.AppendLine("global using Color = Windows.UI.Color;");
        if (hasViewModelsNamespace)
            sb.AppendLine($"global using {appNamespace}.ViewModels;");
        return new OutputFile("GlobalUsings.g.cs", sb.ToString());
    }

    public static OutputFile GenerateAppXaml(
        AppDecl app,
        string appNamespace,
        string? stylesSource)
    {
        var sb = new StringBuilder();
        var theme = app.Members.OfType<ThemeBlock>().FirstOrDefault();

        var dslStyles = theme?.Properties.FirstOrDefault(p => p.Key == "styles")?.Value as StringValue;
        var resolvedPath = stylesSource
                           ?? dslStyles?.Value
                           ?? "ms-appx:///Flagstaff.Stdlib/Styles.xaml";

        sb.AppendLine("<!-- Auto-generated by Flagstaff — overwritten on next flagstaff compile. -->");
        sb.AppendLine("<Application");
        sb.AppendLine($"    x:Class=\"{appNamespace}.App\"");
        sb.AppendLine("    xmlns=\"http://schemas.microsoft.com/winfx/2006/xaml/presentation\"");
        sb.AppendLine("    xmlns:x=\"http://schemas.microsoft.com/winfx/2006/xaml\"");
        sb.AppendLine($"    xmlns:local=\"using:{appNamespace}\">");
        sb.AppendLine("    <Application.Resources>");
        sb.AppendLine("        <ResourceDictionary>");
        sb.AppendLine("            <ResourceDictionary.MergedDictionaries>");
        sb.AppendLine("                <XamlControlsResources xmlns=\"using:Microsoft.UI.Xaml.Controls\" />");
        sb.AppendLine($"                <ResourceDictionary Source=\"{resolvedPath}\" />");
        sb.AppendLine("            </ResourceDictionary.MergedDictionaries>");

        if (theme is not null)
        {
            foreach (var prop in theme.Properties)
            {
                if (prop.Key == "accent" && prop.Value is ColorValue color)
                {
                    var family = ColorUtility.ComputeAccentFamily(color.Hex);
                    sb.AppendLine($"            <Color x:Key=\"SystemAccentColor\">{family[0]}</Color>");
                    sb.AppendLine($"            <Color x:Key=\"SystemAccentColorLight1\">{family[1]}</Color>");
                    sb.AppendLine($"            <Color x:Key=\"SystemAccentColorLight2\">{family[2]}</Color>");
                    sb.AppendLine($"            <Color x:Key=\"SystemAccentColorLight3\">{family[3]}</Color>");
                    sb.AppendLine($"            <Color x:Key=\"SystemAccentColorDark1\">{family[4]}</Color>");
                    sb.AppendLine($"            <Color x:Key=\"SystemAccentColorDark2\">{family[5]}</Color>");
                    sb.AppendLine($"            <Color x:Key=\"SystemAccentColorDark3\">{family[6]}</Color>");
                    sb.AppendLine($"            <SolidColorBrush x:Key=\"FlagstaffAccentBrush\" Color=\"{{StaticResource SystemAccentColor}}\" />");
                }
                else if (prop.Key == "font" && prop.Value is StringValue font)
                {
                    sb.AppendLine($"            <x:String x:Key=\"FlagstaffFontFamily\">{font.Value}</x:String>");
                }
            }
        }

        sb.AppendLine($"            <local:BoolToVisibilityConverter x:Key=\"BoolToVisibility\" />");
        sb.AppendLine($"            <local:CurrencyConverter x:Key=\"CurrencyConverter\" />");
        sb.AppendLine($"            <local:PercentConverter x:Key=\"PercentConverter\" />");
        sb.AppendLine($"            <local:DateConverter x:Key=\"DateConverter\" />");
        sb.AppendLine($"            <local:NumberConverter x:Key=\"NumberConverter\" />");
        sb.AppendLine("        </ResourceDictionary>");
        sb.AppendLine("    </Application.Resources>");
        sb.AppendLine("</Application>");

        return new OutputFile("App.xaml", sb.ToString());
    }

    public static OutputFile GenerateAppXamlCs(
        string appNamespace,
        List<string> viewModelTypes)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Flagstaff — overwritten on next flagstaff compile.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine("using Microsoft.UI.Xaml;");
        sb.AppendLine();
        sb.AppendLine($"namespace {appNamespace};");
        sb.AppendLine();
        sb.AppendLine("public partial class App : Application");
        sb.AppendLine("{");
        sb.AppendLine("    public static IServiceProvider Services { get; private set; } = null!;");
        sb.AppendLine("    public static MainWindow? MainWindow { get; private set; }");
        sb.AppendLine("    public static T GetService<T>() where T : class => Services.GetRequiredService<T>();");
        sb.AppendLine();
        sb.AppendLine("    public App() { InitializeComponent(); }");
        sb.AppendLine();
        sb.AppendLine("    protected override async void OnLaunched(LaunchActivatedEventArgs args)");
        sb.AppendLine("    {");
        sb.AppendLine("        var services = new ServiceCollection();");

        foreach (var vmType in viewModelTypes.OrderBy(t => t))
        {
            sb.AppendLine($"        services.AddTransient<ViewModels.{vmType}>();");
        }

        sb.AppendLine("        ConfigureServices(services);");
        sb.AppendLine("        Services = services.BuildServiceProvider();");
        sb.AppendLine();
        sb.AppendLine("        // Async startup work (seeding, migrations, settings) runs here, before the first page loads.");
        sb.AppendLine("        var steps = new List<Func<Task>>();");
        sb.AppendLine("        OnAppStarting(steps);");
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine("            foreach (var step in steps)");
        sb.AppendLine("                await step();");
        sb.AppendLine("        }");
        sb.AppendLine("        catch (Exception ex)");
        sb.AppendLine("        {");
        sb.AppendLine("            System.Diagnostics.Debug.WriteLine($\"[Flagstaff] OnAppStarting step failed: {ex}\");");
        sb.AppendLine("#if DEBUG");
        sb.AppendLine("            throw;");
        sb.AppendLine("#endif");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        MainWindow = new MainWindow();");
        sb.AppendLine("        MainWindow.Activate();");
        sb.AppendLine("        OnAppLaunched();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    partial void ConfigureServices(IServiceCollection services);");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Add async startup steps; they run in order after the services are built, before MainWindow is created.</summary>");
        sb.AppendLine("    partial void OnAppStarting(List<Func<Task>> steps);");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Runs after MainWindow is activated.</summary>");
        sb.AppendLine("    partial void OnAppLaunched();");
        sb.AppendLine("}");

        return new OutputFile("App.xaml.cs", sb.ToString());
    }
}
