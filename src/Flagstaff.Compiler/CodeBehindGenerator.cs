using System.Text;

namespace Flagstaff.Compiler;

/// <summary>
/// Emits minimal .xaml.cs code-behind: constructor + InitializeComponent + DataContext wiring.
/// </summary>
public static class CodeBehindGenerator
{
    public static string GenerateAppCodeBehind(AppDecl app, string appNamespace)
    {
        var hasNav = app.Members.OfType<NavBlock>().Any();
        var theme = app.Members.OfType<ThemeBlock>().FirstOrDefault();
        var titlebar = GetThemeIdent(theme, "titlebar") ?? "extended";
        var useTitleBar = titlebar == "extended" && theme is not null;

        var sb = new StringBuilder();
        sb.AppendLine("// Auto-generated by Flagstaff — overwritten on next flagstaff compile.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using Microsoft.UI.Xaml;");
        if (hasNav)
            sb.AppendLine("using Microsoft.UI.Xaml.Controls;");
        sb.AppendLine();
        sb.AppendLine($"namespace {appNamespace};");
        sb.AppendLine();
        sb.AppendLine("public sealed partial class MainWindow : Window");
        sb.AppendLine("{");
        sb.AppendLine("    public MainWindow()");
        sb.AppendLine("    {");
        sb.AppendLine("        InitializeComponent();");
        if (useTitleBar)
        {
            sb.AppendLine("        ExtendsContentIntoTitleBar = true;");
            sb.AppendLine("        SetTitleBar(AppTitleBar);");
        }
        if (hasNav)
        {
            sb.AppendLine("        NavView.SelectionChanged += OnNavigationChanged;");
            sb.AppendLine("        NavView.Loaded += OnNavViewLoaded;");
        }
        sb.AppendLine("    }");
        if (hasNav)
        {
            sb.AppendLine();
            sb.AppendLine("    private void OnNavViewLoaded(object sender, Microsoft.UI.Xaml.RoutedEventArgs e)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (NavView.MenuItems.Count > 0)");
            sb.AppendLine("            NavView.SelectedItem = NavView.MenuItems[0];");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    private void OnNavigationChanged(NavigationView sender, NavigationViewSelectionChangedEventArgs args)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (args.SelectedItem is NavigationViewItem item && item.Tag is string tag)");
            sb.AppendLine("        {");
            sb.AppendLine("            try");
            sb.AppendLine("            {");
            sb.AppendLine($"                var pageType = Type.GetType($\"{appNamespace}.{{tag}}\");");
            sb.AppendLine("                if (pageType is not null) ContentFrame.Navigate(pageType);");
            sb.AppendLine("            }");
            sb.AppendLine("            catch (Exception ex)");
            sb.AppendLine("            {");
            sb.AppendLine("                System.Diagnostics.Debug.WriteLine($\"[Flagstaff] Navigation to {tag} failed: {ex}\");");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Emits the Page code-behind. <paramref name="conditions"/> must be the instance the XAML was
    /// generated with (its compiled When_n/Enabled_n functions are emitted here); when null, the
    /// XAML is generated internally to collect them.
    /// </summary>
    public static string GenerateViewCodeBehind(ViewDecl view, string appNamespace, ConditionCompiler? conditions = null, IEnumerable<string>? extraMembers = null,
        ViewContract? contract = null)
    {
        if (conditions is null)
        {
            conditions = new ConditionCompiler(view, TypeInference.InferMembers(view));
            new XamlGenerator().GenerateView(view, appNamespace, conditions);
        }
        var functions = conditions.Functions;

        var sb = new StringBuilder();
        var vmType = view.Binding?.ViewModelType;
        var hasNavButtons = HasNavigateButtons(view.Body);
        var toastTimers = vmType is not null ? CollectToastTimers(view) : [];

        sb.AppendLine("// Auto-generated by Flagstaff — overwritten on next flagstaff compile.");
        contract ??= new ViewContract(view.Name, vmType, view.Location, [], []);
        foreach (var line in contract.PageHeader())
            sb.AppendLine(line);
        sb.AppendLine("#nullable enable");
        if (functions.Any(f => f.Return == ConditionReturn.Visibility))
            sb.AppendLine("using Microsoft.UI.Xaml;");
        sb.AppendLine("using Microsoft.UI.Xaml.Controls;");
        sb.AppendLine();
        sb.AppendLine($"namespace {appNamespace};");
        sb.AppendLine();
        sb.AppendLine($"public sealed partial class {view.Name} : Page");
        sb.AppendLine("{");

        AppendConstructors(sb, view.Name, vmType, toastTimers.Count > 0, contract);

        if (hasNavButtons)
        {
            sb.AppendLine();
            sb.AppendLine("    private void OnNavigateButtonClick(object sender, Microsoft.UI.Xaml.RoutedEventArgs e)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (sender is Microsoft.UI.Xaml.FrameworkElement { Tag: string tag })");
            sb.AppendLine("        {");
            sb.AppendLine($"            var pageType = Type.GetType($\"{appNamespace}.{{tag}}\");");
            sb.AppendLine("            if (pageType is not null) Frame.Navigate(pageType);");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
        }

        if (view.OnLoadTarget is not null)
        {
            // onload -> vm.Load; (and the legacy vm.LoadAsync) generate LoadCommand in the .g.cs.
            var stem = TypeInference.OnLoadCommandStem(view.OnLoadTarget);
            sb.AppendLine();
            sb.AppendLine("    private async void OnViewLoaded(object sender, Microsoft.UI.Xaml.RoutedEventArgs e)");
            sb.AppendLine("    {");
            sb.AppendLine("        try");
            sb.AppendLine("        {");
            sb.AppendLine($"            await ViewModel.{stem}Command.ExecuteAsync(null);");
            sb.AppendLine("        }");
            sb.AppendLine("        catch (Exception ex)");
            sb.AppendLine("        {");
            sb.AppendLine($"            System.Diagnostics.Debug.WriteLine($\"[Flagstaff] {view.Name} {stem}Command failed: {{ex}}\");");
            sb.AppendLine("#if DEBUG");
            sb.AppendLine("            throw; // Debug builds surface load failures instead of showing a silently empty page.");
            sb.AppendLine("#endif");
            sb.AppendLine("        }");
            sb.AppendLine("    }");
        }

        if (toastTimers.Count > 0)
            AppendToastTimers(sb, toastTimers);

        foreach (var function in functions)
        {
            sb.AppendLine();
            sb.Append(function.RenderMethod());
        }

        foreach (var member in extraMembers ?? [])
        {
            sb.AppendLine();
            sb.AppendLine(member.TrimEnd());
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// The page's constructors, ViewModel property and the <c>OnViewCreated</c> hook. Default: <c>View()</c> resolves the
    /// ViewModel and chains to <c>View(Vm)</c>, which sets <c>ViewModel</c>, calls <c>InitializeComponent()</c>, wires the
    /// toast timers and calls <c>OnViewCreated()</c>. When the hand-written partial declares <c>View()</c> or
    /// <c>View(Vm)</c> itself (<see cref="ViewContract.UserConstructors"/>), the generated one is skipped, <c>ViewModel</c>
    /// becomes a lazily resolved property (so a constructor of theirs that never sets it still binds), and, when their
    /// constructor does not call <c>InitializeComponent()</c>, <c>OnNavigatedTo</c> calls it (a second call is a no-op).
    /// </summary>
    private static void AppendConstructors(StringBuilder sb, string viewName, string? vmType, bool wireToasts, ViewContract contract)
    {
        var onViewCreated = contract.OnViewCreatedAccessibility.Length > 0 ? contract.OnViewCreatedAccessibility + " " : "";
        if (vmType is null)
        {
            if (!contract.HasUserParameterlessConstructor)
            {
                sb.AppendLine($"    public {viewName}()");
                sb.AppendLine("    {");
                sb.AppendLine("        InitializeComponent();");
                sb.AppendLine("        OnViewCreated();");
                sb.AppendLine("    }");
                sb.AppendLine();
            }
        }
        else if (contract.UserConstructors.Count == 0)
        {
            if (contract.UserViewModelProperty is null)
            {
                sb.AppendLine($"    public ViewModels.{vmType} ViewModel {{ get; }}");
                sb.AppendLine();
            }
            sb.AppendLine($"    public {viewName}() : this(App.GetService<ViewModels.{vmType}>()) {{ }}");
            sb.AppendLine();
            sb.AppendLine($"    public {viewName}(ViewModels.{vmType} viewModel)");
            sb.AppendLine("    {");
            sb.AppendLine("        ViewModel = viewModel;");
            sb.AppendLine("        InitializeComponent();");
            if (wireToasts)
                sb.AppendLine("        ViewModel.PropertyChanged += OnToastFlagChanged;");
            sb.AppendLine("        OnViewCreated();");
            sb.AppendLine("    }");
            sb.AppendLine();
        }
        else
        {
            sb.AppendLine($"    // Your constructor in {contract.UserConstructors[0].File} replaces the generated one; ViewModel resolves on first use.");
            if (contract.UserViewModelProperty is null)
            {
                string Wire(string value) => wireToasts ? $"WireViewModel({value})" : value;
                sb.AppendLine($"    public ViewModels.{vmType} ViewModel");
                sb.AppendLine("    {");
                sb.AppendLine($"        get => _viewModel ??= {Wire($"App.GetService<ViewModels.{vmType}>()")};");
                sb.AppendLine($"        private set => _viewModel = {Wire("value")};");
                sb.AppendLine("    }");
                sb.AppendLine();
                sb.AppendLine($"    private ViewModels.{vmType}? _viewModel;");
                sb.AppendLine();
                if (wireToasts)
                {
                    sb.AppendLine($"    private ViewModels.{vmType} WireViewModel(ViewModels.{vmType} viewModel)");
                    sb.AppendLine("    {");
                    sb.AppendLine("        viewModel.PropertyChanged += OnToastFlagChanged;");
                    sb.AppendLine("        return viewModel;");
                    sb.AppendLine("    }");
                    sb.AppendLine();
                }
            }
            if (!contract.HasUserParameterlessConstructor)
            {
                sb.AppendLine($"    public {viewName}() : this(App.GetService<ViewModels.{vmType}>()) {{ }}");
                sb.AppendLine();
            }
            if (!contract.HasUserViewModelConstructor)
            {
                sb.AppendLine($"    public {viewName}(ViewModels.{vmType} viewModel)");
                sb.AppendLine("    {");
                sb.AppendLine("        ViewModel = viewModel;");
                sb.AppendLine("        InitializeComponent();");
                sb.AppendLine("        OnViewCreated();");
                sb.AppendLine("    }");
                sb.AppendLine();
            }
        }

        if (contract.UserConstructors.Count > 0 && contract.NeedsInitializeFallback)
        {
            sb.AppendLine("    // Your constructor does not call InitializeComponent(); it runs here instead (a second call is a no-op).");
            sb.AppendLine("    protected override void OnNavigatedTo(Microsoft.UI.Xaml.Navigation.NavigationEventArgs e)");
            sb.AppendLine("    {");
            sb.AppendLine("        InitializeComponent();");
            sb.AppendLine("        base.OnNavigatedTo(e);");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

        sb.AppendLine($"    {onViewCreated}partial void OnViewCreated();");
    }

    private static string? GetThemeIdent(ThemeBlock? theme, string key)
    {
        if (theme is null) return null;
        var prop = theme.Properties.FirstOrDefault(p => p.Key == key);
        return prop?.Value switch
        {
            IdentValue iv => iv.Name,
            StringValue sv => sv.Value,
            _ => null
        };
    }

    /// <summary>A <c>toast ... when(vm.Flag) duration: ms;</c> that the code-behind auto-dismisses.</summary>
    private sealed record ToastTimer(string Flag, int Milliseconds, Element Toast);

    /// <summary>Toasts with <c>duration:</c> and a bare <c>when(vm.Flag)</c>, one per flag (first wins), document order.</summary>
    private static List<ToastTimer> CollectToastTimers(ViewDecl view)
    {
        var timers = new List<ToastTimer>();
        foreach (var (el, inTemplate) in XamlGenerator.CollectOverlays(view))
        {
            if (inTemplate || el.Keyword != "toast")
                continue;
            if (el.Props.FirstOrDefault(p => p.Key == "duration")?.Value is not IntValue duration)
                continue;
            if (el.When is not PathCond { Path: var path } || !path.StartsWith("vm.", StringComparison.Ordinal))
                continue; // FS2003 / FS1021
            var flag = path["vm.".Length..];
            if (timers.All(t => t.Flag != flag))
                timers.Add(new ToastTimer(flag, duration.Value, el));
        }
        return timers;
    }

    /// <summary>
    /// When a toast flag becomes true, (re)start a one-shot DispatcherQueueTimer that sets it back to false.
    /// One field + one Restart method per toast; the PropertyChanged handler dispatches by property name.
    /// </summary>
    private static void AppendToastTimers(StringBuilder sb, List<ToastTimer> timers)
    {
        sb.AppendLine();
        sb.AppendLine("    // Auto-dismiss for toast ... duration: — restarted each time the flag becomes true.");
        sb.AppendLine("    private void OnToastFlagChanged(object? sender, System.ComponentModel.PropertyChangedEventArgs e)");
        sb.AppendLine("    {");
        sb.AppendLine("        switch (e.PropertyName)");
        sb.AppendLine("        {");
        foreach (var t in timers)
        {
            sb.AppendLine($"            case nameof(ViewModel.{t.Flag}) when ViewModel.{t.Flag}:");
            sb.AppendLine($"                Restart{t.Flag}Timer();");
            sb.AppendLine("                break;");
        }
        sb.AppendLine("        }");
        sb.AppendLine("    }");

        foreach (var t in timers)
        {
            var field = "_" + char.ToLowerInvariant(t.Flag[0]) + t.Flag[1..] + "Timer";
            sb.AppendLine();
            sb.AppendLine($"    private Microsoft.UI.Dispatching.DispatcherQueueTimer? {field};");
            sb.AppendLine();
            sb.AppendLine($"    // toast \"{CommentLabel(t.Toast)}\" duration: {t.Milliseconds} at {t.Toast.Location.ToShortString()}");
            sb.AppendLine($"    private void Restart{t.Flag}Timer()");
            sb.AppendLine("    {");
            sb.AppendLine($"        if ({field} is null)");
            sb.AppendLine("        {");
            sb.AppendLine($"            {field} = DispatcherQueue.CreateTimer();");
            sb.AppendLine($"            {field}.Interval = TimeSpan.FromMilliseconds({t.Milliseconds});");
            sb.AppendLine($"            {field}.IsRepeating = false;");
            sb.AppendLine($"            {field}.Tick += (_, _) => ViewModel.{t.Flag} = false;");
            sb.AppendLine("        }");
            sb.AppendLine($"        {field}.Stop();");
            sb.AppendLine($"        {field}.Start();");
            sb.AppendLine("    }");
        }
    }

    /// <summary>The toast's label, safe for a one-line C# comment.</summary>
    private static string CommentLabel(Element el) =>
        (el.Props.FirstOrDefault(p => p.Key == "_label")?.Value is StringValue sv ? sv.Value : "")
            .ReplaceLineEndings(" ");

    private static bool HasNavigateButtons(List<Element> elements)
    {
        foreach (var el in elements)
        {
            // confirm -> navigate(View) emits a navigating OK button; link/filePicker navigate like buttons.
            if (el.Keyword is "button" or "confirm" or "link" or "filePicker" && el.NavTarget is { } target
                && !target.StartsWith("vm.", StringComparison.Ordinal) && target != XamlGenerator.CancelTarget)
                return true;
            // Property-element values (`Flyout: Flyout { button "Open" -> navigate(V); }`) too.
            foreach (var prop in el.Props)
            {
                if (prop.Value is ElementValue ev && HasNavigateButtons([ev.Element])
                    || prop.Value is ElementsValue evs && HasNavigateButtons(evs.Elements))
                    return true;
            }
            if (el.Body is BlockBody block)
            {
                foreach (var child in block.Children)
                {
                    if (child is ChildElement ce && HasNavigateButtons([ce.Element]))
                        return true;
                }
            }
        }
        return false;
    }
}
