namespace Flagstaff.Compiler;

// Page root and layout/container elements.
public sealed partial class XamlGenerator
{
    /// <summary>
    /// Emits the Page XAML for a view. Pass the same <paramref name="conditions"/> instance to
    /// <see cref="CodeBehindGenerator.GenerateViewCodeBehind"/> so the When_n/Enabled_n functions match.
    /// <para>
    /// Page root: a Grid with an Auto row (the first top-level <c>toolbar</c>, pinned) and a <c>*</c> row
    /// (the body). The body scrolls (<c>ScrollViewer &gt; StackPanel</c>) unless a top-level element has
    /// bare <c>fill</c>; then it is a Grid whose fill row takes the remaining height.
    /// </para>
    /// </summary>
    public string GenerateView(ViewDecl view, string appNamespace, ConditionCompiler? conditions = null)
    {
        _namespace = appNamespace;
        _sb.Clear();
        _indent = 0;
        Diagnostics.Clear();
        // The condition compiler's members carry hand-written types (DeclaredTypes): the badge's InfoBadge choice uses them.
        var members = conditions?.Members.ToList() ?? TypeInference.InferMembers(view);
        _inferredMembers = members.ToDictionary(m => m.Name);
        _conditions = conditions ?? new ConditionCompiler(view, members);
        _gridSized.Clear();
        _passThroughEmitted.Clear();
        _propertyElementsEmitted.Clear();
        _placedByWrapper.Clear();
        NumberLoadNames(view);
        Diagnostics.Clear();
        foreach (var diagnostic in LayoutValidator.Validate(view))
            Report(diagnostic);

        var vmType = view.Binding?.ViewModelType;

        Line("<!-- Auto-generated by Flagstaff — overwritten on next flagstaff compile. -->");
        Line($"<Page");
        Indent();
        Line($"x:Class=\"{_namespace}.{view.Name}\"");
        Line("x:Name=\"FlagstaffPage\"");
        WriteXamlNamespaces();
        if (vmType is not null)
            Line($"xmlns:vm=\"using:{_namespace}.ViewModels\"");
        if (view.OnLoadTarget is not null)
            Line("Loaded=\"OnViewLoaded\"");
        Line("Background=\"{ThemeResource ApplicationPageBackgroundThemeBrush}\"");
        Line(">");
        Dedent();

        Indent();
        EmitViewPropertyElements(view);
        Line("<Grid>");
        Indent();
        EmitViewVisualStateGroups(view);
        Line("<Grid.RowDefinitions>");
        Indent();
        Line("<RowDefinition Height=\"Auto\" />");
        Line("<RowDefinition Height=\"*\" />");
        Dedent();
        Line("</Grid.RowDefinitions>");

        var pinned = PinnedToolbar(view);
        if (pinned is not null)
            EmitElement(pinned); // row 0 (the default), outside the scrolling body

        var body = view.Body
            .Where(e => !ReferenceEquals(e, pinned))
            .Select(ElementOrText (e) => new ChildElement(e))
            .ToList();
        if (body.Any(c => c is ChildElement ce && IsFill(ce.Element)))
        {
            EmitVerticalContainer(body, "16", "24", " Grid.Row=\"1\"");
        }
        else
        {
            Line("<ScrollViewer Grid.Row=\"1\">");
            Indent();
            EmitVerticalContainer(body, "16", "24", "");
            Dedent();
            Line("</ScrollViewer>");
        }
        EmitOverlayLayer(view);
        Dedent();
        Line("</Grid>");
        Dedent();

        Line("</Page>");
        ReportUnsupportedPassThrough(view);
        ReportUnemittedEvents(view);
        return _sb.ToString();
    }

    /// <summary>The first top-level <c>toolbar</c>; it is pinned above the scrolling body.</summary>
    internal static Element? PinnedToolbar(ViewDecl view) => view.Body.FirstOrDefault(e => e.Keyword == "toolbar");

    /// <summary>
    /// A vertical container (page body, <c>stack</c>/<c>column</c>, <c>group</c>, <c>card</c>): a StackPanel,
    /// or, when a child has bare <c>fill</c>, a Grid with one RowDefinition per child (<c>Auto</c>, <c>*</c>
    /// for the fill child). <paramref name="header"/> emits an optional first row (group/card title); it
    /// receives the attributes to append to its root tag.
    /// </summary>
    /// <param name="owner">The keyword element whose root tag this container is (<c>stack</c>, <c>group</c>), so its
    /// property elements are written inside it (<see cref="EmitRoot"/>); null for the page body and a card's content.</param>
    private void EmitVerticalContainer(IReadOnlyList<ElementOrText> children, string? spacing, string? padding,
        string extraAttrs, Action<string>? header = null, Element? owner = null)
    {
        var pad = padding is not null ? $" Padding=\"{padding}\"" : "";
        var hasFill = children.Any(c => c is ChildElement ce && !IsHoisted(ce.Element) && IsFill(ce.Element));

        if (!hasFill)
        {
            var space = spacing is not null ? $" Spacing=\"{spacing}\"" : "";
            Root("StackPanel", $"{space}{pad}{extraAttrs}", () =>
            {
                header?.Invoke("");
                foreach (var child in children)
                    EmitStackChild(child, "");
            });
            return;
        }

        var rowSpacing = spacing is not null ? $" RowSpacing=\"{spacing}\"" : "";
        Root("Grid", $"{rowSpacing}{pad}{extraAttrs}", () =>
        {
            Line("<Grid.RowDefinitions>");
            Indent();
            if (header is not null)
                Line("<RowDefinition Height=\"Auto\" />");
            foreach (var child in children)
            {
                if (child is ChildElement { Element: var hoisted } && IsHoisted(hoisted))
                    continue; // overlay layer: no row
                var height = child is ChildElement ce && IsFill(ce.Element) ? "*" : "Auto";
                Line($"<RowDefinition Height=\"{height}\" />");
            }
            Dedent();
            Line("</Grid.RowDefinitions>");

            int row = 0;
            if (header is not null)
                header($" Grid.Row=\"{row++}\"");
            foreach (var child in children)
            {
                if (child is ChildElement { Element: var hoisted } && IsHoisted(hoisted))
                    EmitElement(hoisted); // marker comment only
                else
                    EmitStackChild(child, $" Grid.Row=\"{row++}\"");
            }
        });

        void Root(string tag, string attrs, Action body)
        {
            if (owner is not null)
                EmitRoot(owner, tag, attrs, body);
            else
                EmitTag(tag, attrs, body);
        }
    }

    /// <summary>Emits one child of a vertical container; <paramref name="slot"/> is its Grid.Row attribute (or "").</summary>
    private void EmitStackChild(ElementOrText child, string slot)
    {
        switch (child)
        {
            case TextContent tc:
                Line($"<TextBlock Text=\"{Esc(tc.Text)}\" TextWrapping=\"Wrap\"{slot} />");
                break;
            case ChildElement { Element.Keyword: "spacer" } ce:
                EmitSpacer(ce.Element, slot);
                break;
            case ChildElement ce when slot.Length == 0:
                EmitElement(ce.Element);
                break;
            case ChildElement ce:
                EmitInSlot(ce.Element, slot);
                break;
        }
    }

    /// <summary>Wraps a child in a lightweight Border that carries its Grid placement, so emitters stay context-free.</summary>
    private void EmitInSlot(Element el, string slot)
    {
        Line($"<Border{slot}>");
        Indent();
        EmitElement(el);
        Dedent();
        Line("</Border>");
    }

    private static List<ElementOrText> BlockChildren(Element el) =>
        el.Body is BlockBody block ? block.Children : [];

    private void EmitToolbar(Element el)
    {
        EmitRoot(el, "Grid", $" Style=\"{{StaticResource FlagstaffToolbar}}\"{CommonAttrs(el)}", () => EmitToolbarBody(el));
    }

    private void EmitToolbarBody(Element el)
    {
        Line("<Grid.ColumnDefinitions>");
        Indent();
        Line("<ColumnDefinition Width=\"Auto\" />");
        Line("<ColumnDefinition Width=\"*\" />");
        Line("<ColumnDefinition Width=\"Auto\" />");
        Dedent();
        Line("</Grid.ColumnDefinitions>");

        if (el.Body is BlockBody block)
        {
            var leftItems = new List<Element>();
            var rightItems = new List<Element>();
            bool seenSpacer = false;
            foreach (var child in block.Children)
            {
                if (child is ChildElement { Element.Keyword: "spacer" })
                {
                    seenSpacer = true;
                    continue;
                }
                if (child is ChildElement ce)
                    (seenSpacer ? rightItems : leftItems).Add(ce.Element);
            }

            if (leftItems.Count > 0)
            {
                Line("<StackPanel Grid.Column=\"0\" Orientation=\"Horizontal\" Spacing=\"8\">");
                Indent();
                foreach (var item in leftItems)
                    EmitElement(item);
                Dedent();
                Line("</StackPanel>");
            }

            if (rightItems.Count > 0)
            {
                Line("<StackPanel Grid.Column=\"2\" Orientation=\"Horizontal\" Spacing=\"8\">");
                Indent();
                foreach (var item in rightItems)
                    EmitElement(item);
                Dedent();
                Line("</StackPanel>");
            }
        }
    }

    private void EmitHeading(Element el)
    {
        var raw = RawBinding(el, "_binding");
        var text = raw is not null ? BindExpr(raw) : Esc(GetLabel(el));
        var symbol = GetIconSymbol(el.Props);
        var attrs = CommonAttrs(el);
        if (symbol is not null)
        {
            EmitRoot(el, "StackPanel", $" Orientation=\"Horizontal\" Spacing=\"8\"{attrs}", () =>
            {
                Line($"<SymbolIcon Symbol=\"{symbol}\" />");
                Line($"<TextBlock Text=\"{text}\" Style=\"{{StaticResource SubtitleTextBlockStyle}}\" />");
            });
        }
        else
        {
            EmitRoot(el, "TextBlock", $" Text=\"{text}\" Style=\"{{StaticResource SubtitleTextBlockStyle}}\"{attrs}", null);
        }
    }

    /// <summary>
    /// Spacer reached through <c>EmitElement</c> (e.g. inside an alert): a fixed vertical gap. Vertical
    /// containers call <see cref="EmitSpacer(Element, string)"/> instead (keeps its when()/props);
    /// toolbar, row and split handle spacers structurally.
    /// </summary>
    private void EmitSpacer() => Line("<Border Height=\"16\" />");

    private void EmitSpacer(Element el, string slot) => Line($"<Border Height=\"16\"{slot}{CommonAttrs(el)} />");

    private void EmitSeparator(Element el) =>
        EmitRoot(el, "Border", $" Height=\"1\" Background=\"{{ThemeResource DividerStrokeColorDefaultBrush}}\"{CommonAttrs(el)}", null);

    private void EmitText(Element el)
    {
        var binding = RawBinding(el, "_binding");
        var label = GetLabel(el);
        var attrs = CommonAttrs(el);
        if (el.Props.Any(p => p.Key == "bold") && el.Props.All(p => p.Key != "FontWeight"))
            attrs = " FontWeight=\"Bold\"" + attrs;
        if (binding is not null)
            EmitRoot(el, "TextBlock", $" Text=\"{BindExpr(binding, FormatConverter(el.Format))}\"{attrs}", null);
        else
            EmitRoot(el, "TextBlock", $" Text=\"{Esc(label)}\"{attrs}", null);
    }

    /// <summary>One child's cell in a <c>row</c>/<c>cards</c> grid.</summary>
    internal sealed record GridSlot(Element Element, int Row, int Column, int Span);

    /// <summary>
    /// Places children left to right; <c>span: N</c> advances the column counter by N. With
    /// <paramref name="wrap"/>, a child that does not fit starts a new row. Without it, overflowing
    /// children keep counting past <paramref name="cols"/> (FS1011).
    /// </summary>
    internal static List<GridSlot> LayoutGrid(IEnumerable<Element> children, int cols, bool wrap)
    {
        var slots = new List<GridSlot>();
        int row = 0, col = 0;
        foreach (var child in children)
        {
            var span = Math.Max(1, GetIntProp(child, "span") ?? 1);
            if (wrap && col > 0 && col + span > cols)
            {
                row++;
                col = 0;
            }
            slots.Add(new GridSlot(child, row, col, span));
            col += span;
        }
        return slots;
    }

    internal static List<Element> ChildElements(Element el) =>
        el.Body is BlockBody block ? block.Children.OfType<ChildElement>().Select(c => c.Element).ToList() : [];

    /// <summary>The children that take a grid slot: <see cref="ChildElements"/> without hoisted overlays.</summary>
    internal static List<Element> SlotChildren(Element el) => ChildElements(el).Where(c => !IsHoisted(c)).ToList();

    /// <summary>Marker comments for the hoisted overlays among a grid container's children (they take no slot).</summary>
    private void EmitHoistedMarkers(Element el)
    {
        foreach (var child in ChildElements(el).Where(IsHoisted))
            EmitHoistedMarker(child);
    }

    /// <summary>Column count of a <c>row</c>: <c>cols:</c>, else the children's total span.</summary>
    internal static int RowColumns(Element el) =>
        GetIntProp(el, "cols") ?? Math.Max(1, SlotChildren(el).Sum(c => Math.Max(1, GetIntProp(c, "span") ?? 1)));

    internal static bool RowWraps(Element el) => Prop(el, "wrap") is BoolValue { Value: true };

    /// <summary>Column count of <c>cards</c> (default 4).</summary>
    internal static int CardsColumns(Element el) => GetIntProp(el, "cols") ?? 4;

    private void EmitRow(Element el) => EmitGrid(el, RowColumns(el), RowWraps(el));

    private void EmitCards(Element el) => EmitGrid(el, CardsColumns(el), wrap: true);

    /// <summary>
    /// <c>row</c> / <c>cards</c>: column widths from the children's <c>width:</c> (default <c>*</c>; the first
    /// child placed in a column decides), <c>ColumnSpacing="12"</c>; when wrapping, one Auto row per line
    /// and <c>RowSpacing="12"</c>. A <c>spacer</c> child is an empty column.
    /// </summary>
    private void EmitGrid(Element el, int cols, bool wrap)
    {
        var slots = LayoutGrid(SlotChildren(el), cols, wrap);
        var widths = Enumerable.Repeat("*", cols).ToArray();
        var sized = new bool[cols];
        foreach (var slot in slots)
        {
            if (slot.Column >= cols)
                continue;
            var width = SlotWidth(slot.Element);
            if (!sized[slot.Column] && Prop(slot.Element, "width") is not null)
            {
                widths[slot.Column] = width;
                sized[slot.Column] = true;
            }
        }

        var rows = slots.Count > 0 ? slots.Max(s => s.Row) + 1 : 1;
        var rowSpacing = wrap ? " RowSpacing=\"12\"" : "";
        EmitRoot(el, "Grid", $" ColumnSpacing=\"12\"{rowSpacing}{CommonAttrs(el)}", () =>
        {
            Line("<Grid.ColumnDefinitions>");
            Indent();
            foreach (var width in widths)
                Line($"<ColumnDefinition Width=\"{width}\" />");
            Dedent();
            Line("</Grid.ColumnDefinitions>");
            if (wrap)
            {
                Line("<Grid.RowDefinitions>");
                Indent();
                for (int r = 0; r < rows; r++)
                    Line("<RowDefinition Height=\"Auto\" />");
                Dedent();
                Line("</Grid.RowDefinitions>");
            }

            foreach (var slot in slots)
            {
                if (slot.Element.Keyword == "spacer")
                    continue;
                var attrs = $" Grid.Column=\"{slot.Column}\"";
                if (slot.Span > 1)
                    attrs += $" Grid.ColumnSpan=\"{slot.Span}\"";
                if (wrap)
                    attrs += $" Grid.Row=\"{slot.Row}\"";
                EmitInSlot(slot.Element, attrs);
            }
            EmitHoistedMarkers(el);
        });
    }

    /// <summary><c>stack</c> and its alias <c>column</c>.</summary>
    private void EmitStack(Element el) => EmitVerticalContainer(BlockChildren(el), "8", null, CommonAttrs(el), owner: el);

    private void EmitColumn(Element el) => EmitStack(el);

    /// <summary><c>split</c>: one column per child (at least two), widths from <c>width:</c> (default <c>*</c>), <c>ColumnSpacing="16"</c>.</summary>
    private void EmitSplit(Element el)
    {
        var children = SlotChildren(el);
        var cols = Math.Max(2, children.Count);
        EmitRoot(el, "Grid", $" ColumnSpacing=\"16\"{CommonAttrs(el)}", () =>
        {
            Line("<Grid.ColumnDefinitions>");
            Indent();
            for (int i = 0; i < cols; i++)
                Line($"<ColumnDefinition Width=\"{(i < children.Count ? SlotWidth(children[i]) : "*")}\" />");
            Dedent();
            Line("</Grid.ColumnDefinitions>");
            for (int i = 0; i < children.Count; i++)
            {
                if (children[i].Keyword != "spacer")
                    EmitInSlot(children[i], $" Grid.Column=\"{i}\"");
            }
            EmitHoistedMarkers(el);
        });
    }

    private void EmitGroup(Element el)
    {
        var label = GetLabel(el);
        Action<string>? header = string.IsNullOrEmpty(label)
            ? null
            : slot => Line($"<TextBlock Text=\"{Esc(label)}\" Style=\"{{StaticResource BodyStrongTextBlockStyle}}\"{slot} />");
        EmitVerticalContainer(BlockChildren(el), "4", null, CommonAttrs(el), header, owner: el);
    }

    private void EmitCard(Element el)
    {
        var label = GetLabel(el);
        var attrs = $" Style=\"{{StaticResource FlagstaffCard}}\"{CommonAttrs(el)}";
        Action<string>? header = null;
        if (!string.IsNullOrEmpty(label))
        {
            var symbol = GetIconSymbol(el.Props);
            header = slot =>
            {
                if (symbol is not null)
                {
                    Line($"<StackPanel Orientation=\"Horizontal\" Spacing=\"8\"{slot}>");
                    Indent();
                    Line($"<SymbolIcon Symbol=\"{symbol}\" />");
                    Line($"<TextBlock Text=\"{Esc(label)}\" Style=\"{{StaticResource BodyStrongTextBlockStyle}}\" />");
                    Dedent();
                    Line("</StackPanel>");
                }
                else
                {
                    Line($"<TextBlock Text=\"{Esc(label)}\" Style=\"{{StaticResource BodyStrongTextBlockStyle}}\"{slot} />");
                }
            };
        }
        EmitRoot(el, "Border", attrs, () => EmitVerticalContainer(BlockChildren(el), "8", null, "", header));
    }

    /// <summary>Emits a block's children in order (text content as wrapping TextBlocks). Used by summary.</summary>
    private void EmitBlockChildren(Element el)
    {
        foreach (var child in BlockChildren(el))
            EmitStackChild(child, "");
    }
}
